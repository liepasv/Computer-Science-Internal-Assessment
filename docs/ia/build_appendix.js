// ============================================================
// build_appendix.js — Appendix A: the full source code with line
// numbers, so that every excerpt in the report can be found.
//
//   NODE_PATH=$(npm root -g) node docs/ia/build_appendix.js
// ============================================================

const fs = require("fs");
const path = require("path");
const { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, Footer, PageNumber } = require("docx");

const ROOT = path.resolve(__dirname, "..", "..");
const OUT = path.join(__dirname, "IA_Appendix_A_Source_Code.docx");

const groups = [
    ["Application", ["index.html", "src/csv.js", "src/storage.js", "src/i18n.js", "src/bank.js",
                     "src/session.js", "src/ui.js", "src/history.js", "src/app.js",
                     "tailwind.config.js", "css/input.css"]],
    ["Tests and tools", ["tests/test.html", "tests/run_tests.js", "tools/make_test_data.py",
                         "tools/compare_shuffles.js", "tools/build_en_bank.py"]],
];

const children = [
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 2000, after: 200 }, children: [new TextRun({ text: "Appendix A — Full source code", bold: true, size: 40 })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: "Driving Theory Practice — IB Computer Science Internal Assessment", size: 24 })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 400 }, children: [new TextRun({ text: "Candidate: Liepa Šveikauskaitė", size: 24 })] }),
    new Paragraph({ children: [new TextRun({ text: "Line numbers match the excerpts in the report. Not printed: css/styles.css (generated by Tailwind from tailwind.config.js, minified), the question banks database/db.lt.csv and database/db.en.csv, the pictures in assets/, the test data in tests/data/ and the translation batches in tools/translations/; they are part of the submitted project folder.", size: 20 })] }),
];

groups.forEach(function ([title, files]) {
    children.push(new Paragraph({ heading: HeadingLevel.HEADING_1, pageBreakBefore: true, children: [new TextRun(title)] }));
    files.forEach(function (file, i) {
        const lines = fs.readFileSync(path.join(ROOT, file), "utf8").replace(/\n$/, "").split("\n");
        children.push(new Paragraph({ heading: HeadingLevel.HEADING_2, pageBreakBefore: i > 0, children: [new TextRun(file + "  (" + lines.length + " lines)")] }));
        const width = String(lines.length).length;
        lines.forEach(function (line, n) {
            children.push(new Paragraph({ spacing: { after: 0, line: 220 }, children: [
                new TextRun({ text: String(n + 1).padStart(width, " ") + "  ", font: "Consolas", size: 14, color: "888888" }),
                new TextRun({ text: line.replace(/\t/g, "    "), font: "Consolas", size: 14 })
            ] }));
        });
    });
});

const doc = new Document({
    styles: {
        default: { document: { run: { font: "Arial", size: 20 } } },
        paragraphStyles: [
            { id: "Heading1", name: "Heading 1", basedOn: "Normal", next: "Normal", quickFormat: true, run: { size: 32, bold: true, color: "1F3A68" }, paragraph: { spacing: { after: 200 }, outlineLevel: 0 } },
            { id: "Heading2", name: "Heading 2", basedOn: "Normal", next: "Normal", quickFormat: true, run: { size: 24, bold: true, color: "1F3A68" }, paragraph: { spacing: { before: 120, after: 120 }, outlineLevel: 1 } },
        ]
    },
    sections: [{
        properties: { page: { size: { width: 11906, height: 16838 }, margin: { top: 850, bottom: 850, left: 850, right: 850 } } },
        footers: { default: new Footer({ children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: "Appendix A — page ", size: 16 }), new TextRun({ children: [PageNumber.CURRENT], size: 16 })] })] }) },
        children: children
    }]
});

Packer.toBuffer(doc).then(function (buf) {
    fs.writeFileSync(OUT, buf);
    console.log("Written " + OUT);
});
